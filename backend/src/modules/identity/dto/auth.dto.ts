import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  IsArray,
  IsBoolean,
  IsDefined,
  IsIn,
  IsOptional,
  IsString,
  Length,
  Matches,
  MaxLength,
  ValidateNested,
} from 'class-validator';
import { PLATFORMS, type Platform } from '../../../common/contracts/identity';
import { SessionTokensDto, UserDto } from './common.dto';
import { ConsentChangeDto } from './me.dto';

export class OtpRequestDto {
  @ApiProperty({
    example: '+380501234567',
    description: 'Ukrainian number in any common notation; normalised to E.164',
  })
  @IsString()
  @Length(9, 20)
  phone: string;

  @ApiPropertyOptional({
    description:
      'Installation fingerprint (same value as device.fingerprint at verify); stored for antifraud',
    minLength: 8,
    maxLength: 128,
  })
  @IsOptional()
  @IsString()
  @Length(8, 128)
  fingerprint?: string;

  @ApiPropertyOptional({
    description:
      'Captcha answer; required only after 403 PC_OTP_CAPTCHA_REQUIRED (phone or network over the soft threshold)',
    maxLength: 4096,
  })
  @IsOptional()
  @IsString()
  @MaxLength(4096)
  captchaToken?: string;
}

export class OtpRequestResponseDto {
  @ApiProperty({ example: '+380501234567', description: 'Normalised phone the code was sent to' })
  phone: string;

  @ApiProperty({ format: 'date-time' })
  expiresAt: string;

  @ApiProperty({
    format: 'date-time',
    description:
      'Earliest moment a new code may be requested (resend countdown): cooldown, phone, daily and network limits included',
  })
  resendAvailableAt: string;

  @ApiProperty({ example: 6 })
  codeLength: number;

  @ApiProperty({ example: 5 })
  maxAttempts: number;

  @ApiPropertyOptional({
    description: 'The code itself, returned only when OTP_DEV_ECHO=true (never in production)',
  })
  debugCode?: string;
}

export class DeviceInfoDto {
  @ApiProperty({ enum: PLATFORMS })
  @IsIn(PLATFORMS)
  platform: Platform;

  @ApiPropertyOptional({ example: 'iPhone 15', maxLength: 100 })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  model?: string;

  @ApiPropertyOptional({ example: '1.0.0', maxLength: 32 })
  @IsOptional()
  @IsString()
  @MaxLength(32)
  appVersion?: string;

  @ApiPropertyOptional({
    description: 'Stable installation id generated by the app; reuses the device row on re-login',
    minLength: 8,
    maxLength: 128,
  })
  @IsOptional()
  @IsString()
  @Length(8, 128)
  fingerprint?: string;

  @ApiPropertyOptional({ description: 'FCM/APNs token, if already available', maxLength: 512 })
  @IsOptional()
  @IsString()
  @MaxLength(512)
  pushToken?: string;
}

export class OtpVerifyDto {
  @ApiProperty({ example: '+380501234567' })
  @IsString()
  @Length(9, 20)
  phone: string;

  @ApiProperty({ example: '482913', description: '4-8 digits' })
  @IsString()
  @Matches(/^\d{4,8}$/, { message: 'code must be 4 to 8 digits' })
  code: string;

  @ApiProperty({ type: DeviceInfoDto })
  @IsDefined()
  @ValidateNested()
  @Type(() => DeviceInfoDto)
  device: DeviceInfoDto;

  @ApiPropertyOptional({
    type: [ConsentChangeDto],
    maxItems: 3,
    description:
      'Consents accepted on the login screen (e.g. program terms), applied in the same transaction',
  })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(3)
  @ValidateNested({ each: true })
  @Type(() => ConsentChangeDto)
  consents?: ConsentChangeDto[];
}

export class OtpVerifyResponseDto extends SessionTokensDto {
  @ApiProperty({ description: 'True when this login created the member account' })
  isNewUser: boolean;

  @ApiProperty({ type: UserDto })
  user: UserDto;

  @ApiProperty({ format: 'uuid', description: 'Device bound to the tokens (`did` claim)' })
  deviceId: string;
}

export class RefreshDto {
  @ApiProperty({ description: 'Refresh token returned by otp/verify or the previous refresh' })
  @IsString()
  @Length(20, 256)
  refreshToken: string;
}

export class RefreshResponseDto extends SessionTokensDto {
  @ApiProperty({ type: UserDto })
  user: UserDto;

  @ApiProperty({ nullable: true, type: String, format: 'uuid' })
  deviceId: string | null;
}

export class LogoutDto {
  @ApiPropertyOptional({
    description:
      'Refresh token of the session to end; defaults to the sessions of the current device',
  })
  @IsOptional()
  @IsString()
  @Length(20, 256)
  refreshToken?: string;

  @ApiPropertyOptional({ description: 'End every session of the member on every device' })
  @IsOptional()
  @IsBoolean()
  allDevices?: boolean;
}

export class LogoutResponseDto {
  @ApiProperty({ description: 'Refresh tokens revoked by this call' })
  revokedSessions: number;
}
